const GROUPS = ['Основы', 'Разделы меню', 'Инструменты'];

export default function HelpPage() {
  const router = useRouter();
  const [active, setActive] = useState(SECTIONS[0].id);
  const section = SECTIONS.find((s) => s.id === active) ?? SECTIONS[0];

  return (
    <div
      style={{
        display: 'grid',
        gridTemplateColumns: 'minmax(0, 200px) 1fr',
        gap: 18,
        alignItems: 'start',
      }}
      className="grid-reports"
    >
      <div className="card card-pad" style={{ position: 'sticky', top: 12 }}>
        {GROUPS.map((group) => (
          <div key={group} style={{ marginBottom: 12 }}>
            <div
              className="stat-title"
              style={{ marginBottom: 6, paddingLeft: 2 }}
            >
              {group}
            </div>
            {SECTIONS.filter((s) => s.group === group).map((s) => (
              <button
                key={s.id}
                onClick={() => setActive(s.id)}
                style={{
                  display: 'block',
                  width: '100%',
                  textAlign: 'left',
                  padding: '6px 8px',
                  borderRadius: 7,
                  border: 'none',
                  background: active === s.id ? 'var(--asoft)' : 'transparent',
                  color: active === s.id ? 'var(--accent)' : 'var(--text)',
                  fontSize: '12.5px',
                  fontWeight: active === s.id ? 600 : 400,
                  cursor: 'pointer',
                }}
              >
                {s.title}
              </button>
            ))}
          </div>
        ))}
        <button
          className="btn btn-ghost"
          style={{ width: '100%' }}
          onClick={() => {
            // Тур сам слушает это событие; ключ 'tt_tour_seen' — его признак «показан».
            window.localStorage.removeItem('tt_tour_seen');
            router.push('/dashboard');
            window.dispatchEvent(new Event('tt-open-tour'));
          }}
        >
          Пройти тур заново
        </button>
      </div>

      <div className="card card-pad">
        <h2 style={{ fontSize: 18, margin: '0 0 14px' }}>{section.title}</h2>
        {section.blocks.map((block, i) => (
          <div key={i} style={{ marginBottom: 18 }}>
            {block.heading && (
              <div
                style={{ fontWeight: 600, fontSize: '13.5px', marginBottom: 8 }}
              >
                {block.heading}
              </div>
            )}
            <ul
              style={{
                margin: 0,
                paddingLeft: 18,
                display: 'flex',
                flexDirection: 'column',
                gap: 7,
              }}
            >
              {block.items.map((text, j) => (
                <li
                  key={j}
                  style={{ fontSize: '13px', lineHeight: 1.6, color: 'var(--text)' }}
                >
                  {text}
                </li>
              ))}
            </ul>
          </div>
        ))}
      </div>
    </div>
  );
}
